import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * The WebUIs this worker embeds. Both are served from the portal's own origin
 * (`serveAdminWebUi` / `serveTenantWebUi` in src/static-assets.ts) rather than
 * from a separate dev server, because the admin OAuth callback is pinned to
 * `PORTAL_ORIGIN` — a UI on another port is cut out of the login round trip.
 * The tenant UI joins on the same terms for consistency, not because it has a
 * login of its own.
 *
 * `base` must match the package's `vite.config.ts` `base`: Vite writes that
 * prefix into index.html's asset URLs, and the keys below have to agree with
 * what the browser then requests.
 */
const WEB_UIS = [
  { label: "admin", package: "admin-portal-webui", base: "/admin/", symbol: "ADMIN_UI_ASSETS", output: "ui-assets.generated.ts" },
  { label: "tenant", package: "tenant-portal-webui", base: "/portal/", symbol: "TENANT_UI_ASSETS", output: "tenant-ui-assets.generated.ts" },
];

async function walk(directory, uiDirectory, base, files) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) await walk(fullPath, uiDirectory, base, files);
    else files.push({ path: `${base}${relative(uiDirectory, fullPath).replace(/\\/g, "/")}`, content: (await readFile(fullPath, "utf8")).replace(/\r\n/g, "\n") });
  }
}

async function buildOne(ui) {
  const uiDirectory = join(root, "..", ui.package, "dist");
  const output = join(root, "src", ui.output);
  const files = [];
  await walk(uiDirectory, uiDirectory, ui.base, files);
  files.sort((left, right) => left.path.localeCompare(right.path));
  await mkdir(dirname(output), { recursive: true });
  const entries = files.map(file => `  ${JSON.stringify(file.path)}: ${JSON.stringify(file.content)},`).join("\n");
  await writeFile(output, `// GENERATED by scripts/build-ui-assets.mjs - do not edit.\nexport const ${ui.symbol}: Readonly<Record<string, string>> = {\n${entries}\n};\n`);
  console.log(`${ui.label} ${ui.output}: ${files.length} files`);
}

async function main() {
  for (const ui of WEB_UIS) await buildOne(ui);
}

main().catch(error => { console.error(error); process.exitCode = 1; });
