import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const uiDirectory = join(root, "..", "admin-portal-webui", "dist");
const output = join(root, "src", "ui-assets.generated.ts");

async function walk(directory, files) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) await walk(fullPath, files);
    else files.push({ path: `/admin/${relative(uiDirectory, fullPath).replace(/\\/g, "/")}`, content: (await readFile(fullPath, "utf8")).replace(/\r\n/g, "\n") });
  }
}

async function main() {
  const files = [];
  await walk(uiDirectory, files);
  files.sort((left, right) => left.path.localeCompare(right.path));
  await mkdir(dirname(output), { recursive: true });
  const entries = files.map(file => `  ${JSON.stringify(file.path)}: ${JSON.stringify(file.content)},`).join("\n");
  await writeFile(output, `// GENERATED by scripts/build-ui-assets.mjs - do not edit.\nexport const ADMIN_UI_ASSETS: Readonly<Record<string, string>> = {\n${entries}\n};\n`);
  console.log(`admin ui-assets.generated.ts: ${files.length} files`);
}

main().catch(error => { console.error(error); process.exitCode = 1; });