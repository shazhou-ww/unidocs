/**
 * Generate `src/web-assets.generated.ts` from the built web-psd app
 * (`packages/web-psd/dist`).
 *
 * Same technique as `unicas-packages/admin-webui/scripts/build-ui-assets.mjs`,
 * with one difference: assets are stored base64 rather than utf8, because
 * web-psd ships a binary (`sample.psd`) alongside its HTML/JS. A uniform
 * encoding keeps one code path instead of a text/binary split that would go
 * wrong the first time someone adds a font or a png.
 *
 * Inlining, rather than shipping `dist/` next to the bundle, is what keeps the
 * Docker build untouched: `pnpm deploy --prod` prunes to declared dependencies
 * and esbuild already inlines every workspace import, so a generated module is
 * carried into `dist/main.js` for free.
 *
 * Build order: this script builds web-psd itself rather than declaring a
 * dependency on it. A declared-but-never-imported workspace dependency is
 * exactly what tests/unit/workspace/package-deps.test.mjs rejects, and the
 * relationship here really is build-time-only — nothing in this package
 * imports web-psd's source. Building it here also rules out packaging a stale
 * `dist/` from an earlier checkout.
 */
import { spawnSync } from "node:child_process";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const PKG_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WEB_DIST = join(PKG_ROOT, "..", "web-psd", "dist");
const OUT = join(PKG_ROOT, "src", "web-assets.generated.ts");

async function walk(dir, base, files) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) await walk(full, base, files);
    else {
      files.push({
        path: `/${relative(base, full).replace(/\\/g, "/")}`,
        base64: (await readFile(full)).toString("base64"),
      });
    }
  }
}

function buildWebPsd() {
  const result = spawnSync(
    "pnpm",
    ["--filter", "@unidocs/web-psd", "build"],
    { cwd: join(PKG_ROOT, "..", ".."), stdio: "inherit" },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`web-psd build exited with code ${result.status}`);
  }
}

async function main() {
  buildWebPsd();
  let files = [];
  try {
    await walk(WEB_DIST, WEB_DIST, files);
  } catch (error) {
    // An empty map is a working gateway without a UI, not a broken build —
    // `pnpm --filter @unidocs/azure-gateway build` must stay runnable on its
    // own. The deploy path can't silently ship it though, which is why
    // tests/unit/scripts/azure-web-assets.test.mjs asserts a real build
    // produces a non-empty map.
    console.error(`web-psd dist not built (${error.message}); writing an empty assets map.`);
    files = [];
  }
  files.sort((a, b) => a.path.localeCompare(b.path));
  const entries = files
    .map(file => `  ${JSON.stringify(file.path)}: ${JSON.stringify(file.base64)},`)
    .join("\n");
  const source = `// GENERATED by scripts/build-web-assets.mjs — do not edit.
// Built web-psd assets, base64 keyed by URL path.
export const WEB_ASSETS: Record<string, string> = {
${entries}
};
`;
  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, source, "utf8");
  console.log(`web assets: ${files.length} file(s) -> ${relative(PKG_ROOT, OUT)}`);
}

await main();
