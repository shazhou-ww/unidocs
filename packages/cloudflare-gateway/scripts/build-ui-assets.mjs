/**
 * Generate src/ui-assets.generated.ts from the built gateway webui
 * (packages/web-gateway/dist). Cloudflare Workers cannot read the filesystem
 * at runtime, so the gateway inlines every built UI file as a string keyed by
 * its URL path under the /ui mount. Deploy build order:
 *
 *   pnpm --filter @unidocs/web-gateway build && node scripts/build-ui-assets.mjs && tsc -b
 */

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const UI_DIR = join(ROOT, "..", "web-gateway", "dist");
const OUT = join(ROOT, "src", "ui-assets.generated.ts");

async function readTextAsset(file) {
  return (await readFile(file, "utf8")).replace(/\r\n/g, "\n");
}

async function walk(dir, base, files) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(full, base, files);
    } else {
      const rel = `/${relative(base, full).replace(/\\/g, "/")}`;
      files.push({ rel: `/ui${rel}`, content: await readTextAsset(full) });
    }
  }
}

async function main() {
  let files = [];
  try {
    await walk(UI_DIR, UI_DIR, files);
  } catch (err) {
    console.error(`web-gateway/dist not built (${err.message}); writing an empty assets map.`);
    files = [];
  }
  files.sort((a, b) => a.rel.localeCompare(b.rel));
  await mkdir(dirname(OUT), { recursive: true });
  const body = files
    .map(({ rel, content }) => `  ${JSON.stringify(rel)}: ${JSON.stringify(content)},`)
    .join("\n");
  const ts = `// GENERATED by scripts/build-ui-assets.mjs — do not edit.
// Inlines the built gateway webui (packages/web-gateway/dist) so the Worker
// can serve it at /ui/*.
export const UI_ASSETS: Record<string, string> = {
${body}
};
`;
  await writeFile(OUT, ts);
  console.log(`gateway ui-assets.generated.ts: ${files.length} files`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
