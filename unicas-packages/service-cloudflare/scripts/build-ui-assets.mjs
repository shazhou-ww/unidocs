/**
 * Generate src/admin-bff/ui-assets.generated.ts from the built admin console
 * (admin-webui/dist/ui). Cloudflare Workers cannot read the filesystem at
 * runtime, so the BFF inlines every built UI file as a string keyed by its
 * URL path under the /admin mount (e.g. "/assets/main.js"). The deploy build
 * order is:
 *
 *   pnpm --filter @unicas/admin-webui build:ui && node scripts/build-ui-assets.mjs && tsc -b
 *
 * so `tsc -b` compiles the REAL generated module into dist.
 */

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const UI_DIR = join(ROOT, "..", "admin-webui", "dist", "ui");
const OUT = join(ROOT, "src", "admin-bff", "ui-assets.generated.ts");

/** Read a text asset with LF line endings so the generated module is
 * byte-identical across platforms (Windows checkouts carry CRLF in files). */
async function readTextAsset(file) {
  return (await readFile(file, "utf8")).replace(/\r\n/g, "\n");
}

async function walk(dir, base, files) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(full, base, files);
    } else {
      const rel = `/${relative(base, full).replace(/\\/g, "/")}`;
      files.push({ rel, content: await readTextAsset(full) });
    }
  }
}

async function main() {
  let files = [];
  try {
    await walk(UI_DIR, UI_DIR, files);
  } catch (err) {
    console.error(`admin-webui/dist/ui not built (${err.message}); writing an empty assets map.`);
    files = [];
  }
  // Inline the unicas-cli agent skill alongside the console so agents can
  // fetch it from the deployed /admin/assets/skills/... URL without a
  // repository checkout.
  const SKILL_SOURCES = [
    {
      rel: "/assets/skills/unicas-cli/SKILL.md",
      file: join(ROOT, "..", "..", ".agents", "skills", "unicas-cli", "SKILL.md"),
    },
  ];
  for (const source of SKILL_SOURCES) {
    try {
      files.push({ rel: source.rel, content: await readTextAsset(source.file) });
    } catch (err) {
      console.error(`skill file missing (${err.message}); skipping ${source.rel}`);
    }
  }
  files.sort((a, b) => a.rel.localeCompare(b.rel));
  await mkdir(dirname(OUT), { recursive: true });
  const body = files
    .map(({ rel, content }) => `  ${JSON.stringify(rel)}: ${JSON.stringify(content)},`)
    .join("\n");
  const ts = `// GENERATED by scripts/build-ui-assets.mjs — do not edit.
// Inlines the built admin console (admin-webui/dist/ui) so the Worker can serve it.
export const UI_ASSETS: Record<string, string> = {
${body}
};
`;
  await writeFile(OUT, ts);
  console.log(`ui-assets.generated.ts: ${files.length} files`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
