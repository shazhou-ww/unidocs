/**
 * Generate src/server/ui-assets.generated.ts from the built admin console
 * (dist/ui). Cloudflare Workers cannot read the filesystem at runtime, so the
 * BFF inlines every built UI file as a string keyed by its URL path under the
 * /admin mount (e.g. "/assets/main.js"). The deploy build order is:
 *
 *   vite build && node scripts/build-ui-assets.mjs && tsc
 *
 * so `tsc` compiles the REAL generated module into dist/server.
 */

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const UI_DIR = join(ROOT, "dist", "ui");
const OUT = join(ROOT, "src", "server", "ui-assets.generated.ts");

async function walk(dir, base, files) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(full, base, files);
    } else {
      const rel = `/${relative(base, full).replace(/\\/g, "/")}`;
      files.push({ rel, content: await readFile(full, "utf8") });
    }
  }
}

async function main() {
  let files = [];
  try {
    await walk(UI_DIR, UI_DIR, files);
  } catch (err) {
    console.error(`dist/ui not built (${err.message}); writing an empty assets map.`);
    files = [];
  }
  await mkdir(dirname(OUT), { recursive: true });
  const body = files
    .map(({ rel, content }) => `  ${JSON.stringify(rel)}: ${JSON.stringify(content)},`)
    .join("\n");
  const ts = `// GENERATED by scripts/build-ui-assets.mjs — do not edit.
// Inlines the built admin console (dist/ui) so the Worker can serve it.
export const UI_ASSETS: Record<string, string> = {
${body}
};
`;
  await writeFile(OUT, ts);
  console.log(`ui-assets.generated.ts: ${files.length} files`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
